/**
 * Regenerates `src/client/markdown/katex-css.ts` from the installed `katex`
 * package: `katex/dist/katex.min.css` with every font reference rewritten to
 * a `data:font/woff2` URI (the woff and ttf sources are dropped — every
 * browser the Host supports resolves woff2).
 *
 * The generated module is committed, so builds never need to run this script;
 * after upgrading `katex`, run it once and commit the result together with
 * the dependency bump:
 *
 *     node scripts/generate-katex-css.mjs
 */

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const cssPath = require.resolve("katex/dist/katex.min.css");
const fontsDir = join(dirname(cssPath), "fonts");
const css = readFileSync(cssPath, "utf8");

const font = (name) => readFileSync(join(fontsDir, name)).toString("base64");

const output = css.replace(
  /url\((?:'|")?fonts\/([^'")]+\.woff2)(?:'|")?\)\s*format\((?:'|")?woff2(?:'|")?\)(\s*,\s*url\((?:'|")?fonts\/[^)]+\)\s*format\((?:'|")(?:woff|truetype)(?:'|")?\))*/gu,
  (_, file) => `url(data:font/woff2;base64,${font(file)}) format("woff2")`,
);

const unreplaced = /url\((?:'|")?fonts\//u.test(output);
if (unreplaced) {
  throw new Error("katex.min.css still references font files after rewriting");
}

const target = new URL("../src/client/markdown/katex-css.ts", import.meta.url);
mkdirSync(dirname(fileURLToPath(target)), { recursive: true });
writeFileSync(
  fileURLToPath(target),
  `/**
 * \`katex/dist/katex.min.css\` with every font inlined as a woff2 data URI.
 * Generated by \`scripts/generate-katex-css.mjs\` from the pinned \`katex\`
 * devDependency — do not edit by hand; regenerate after a \`katex\` upgrade.
 *
 * The QA overlay is a self-contained client bundle, so the math styles and
 * their fonts travel inside it: nothing here may reference an external file,
 * and a data URI cannot collide with the Host's own KaTeX font declarations.
 */
export const KATEX_CSS = String.raw\`${output}\`;
`,
  "utf8",
);
console.log(`wrote ${fileURLToPath(target)}`);
